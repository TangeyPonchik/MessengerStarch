def _корень(слово):
    if len(слово) < 4:
        return слово
        
    окончания = [
        "иями", "ями", "ами", "ов", "ев", "ий", "ый", 
        "ая", "ое", "ые", "ых", "ому", "ему", "и", "ы", 
        "а", "я", "у", "ю", "е", "о"
    ]
    
    for оконч in окончания:
        if слово.endswith(оконч):
            return слово[:-len(оконч)]
            
    return слово

def _расстояние(a, b):
    m = len(a)
    n = len(b)
    
    dp = list(range(n + 1))
    
    for i in range(1, m + 1):
        prev = dp[0]
        dp[0] = i
        
        for j in range(1, n + 1):
            temp = dp[j]
            cost = 0 if a[i-1] == b[j-1] else 1
            
            dp[j] = min(
                dp[j] + 1,
                dp[j-1] + 1,
                prev + cost
            )
            prev = temp
            
    return dp[n]

def _похоже(слово, эталон):
    if слово == эталон:
        return True
        
    if abs(len(слово) - len(эталон)) > 2:
        return False
        
    допустимо = 2 if len(эталон) > 5 else 1
    
    return _расстояние(слово, эталон) <= допустимо

