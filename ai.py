def _утилиты(текст):
    # Кубик
    if re.search(r"(кубик|roll)", текст):
        m = re.search(r"(?:кубик|roll)\s*(\d+)?", текст)
        if m:
            грани = int(m.group(1)) if m.group(1) else 6
            if грани > 0 and грани <= 1000:
                return f"🎲 Выпало: {random.randint(1, грани)} (d{грани})"
    
    # Монетка
    if re.search(r"(монет|орёл|решка)", текст):
        return random.choice(["🪙 Орёл!", "🪙 Решка!"])

    # Рандом
    if re.search(r"(рандом|random)\s*(\d+)\s*(\d+)", текст):
        m = re.search(r"(?:рандом|random)\s*(\d+)\s*(\d+)", текст)
        if m:
            a = int(m.group(1))
            b = int(m.group(2))
            минимум = min(a, b)
            максимум = max(a, b)
            return f"🎲 Случайное от {минимум} до {максимум}: {random.randint(минимум, максимум)}"

    # Выбор из вариантов
    if "или" in текст and "?" in текст:
        части = текст.replace("?", "").split(" или ")
        if len(части) == 2:
            выбор = random.choice(части).strip().capitalize()
            return f"Я выбираю: {выбор}!"

    # Пароль
    if "пароль" in текст and ("сгенер" in текст or "придумай" in текст):
        хеш = hashlib.md5(str(random.random()).encode()).hexdigest()
        return f"🔐 Твой пароль: `{хеш[:16]}`"

    # Время
    if re.search(r"\b(время|time)\b", текст):
        сейчас = datetime.now().strftime("%H:%M")
        return f"🕒 Сейчас {сейчас}."

    # Дата
    if re.search(r"\b(дата|date|число)\b", текст):
        сегодня = datetime.now().strftime("%d.%m.%Y")
        return f"📅 Сегодня {сегодня}."

    # Дни до лета
    if re.search(r"сколько.*дней.*до.*лет", текст):
        сегодня = date.today()
        лето = date(сегодня.year, 6, 1)
        if сегодня > лето:
            лето = date(сегодня.year + 1, 6, 1)
        разница = (лето - сегодня).days
        return f"☀️ До лета осталось {разница} дней!"

    # Дни до нового года
    if re.search(r"сколько.*дней.*до.*нового года", текст):
        сегодня = date.today()
        нг = date(сегодня.year + 1, 1, 1)
        разница = (нг - сегодня).days
        return f"🎄 До Нового года осталось {разница} дней!"

    # Математика
    if re.fullmatch(r"[\d\s\+\-\*\/\(\)\.]+", текст):
        try:
            результат = eval(текст, {"__builtins__": {}}, {})
            return f"= {результат}"
        except:
            pass

    # Двоичный код
    if "двоичный" in текст and "код" in текст:
        return "01001000 01100101 01101100 01101100 01101111"

    # Факт
    if "факт" in текст and ("расскажи" in текст or "интересный" in текст):
        факты = [
            "Мёд не портится. Археологи нашли съедобный мёд возрастом 3000 лет.",
            "Осьминоги имеют три сердца.",
            "Венера вращается в обратную сторону по сравнению с другими планетами.",
            "У улиток около 10000 зубов.",
            "Python был назван в честь шоу «Монти Пайтон», а не змеи."
        ]
        return f"💡 {random.choice(факты)}"

    return None

