def ответить(сообщение: str, автор: str, user_id: int = 0, мое_имя: str = "") -> str:
    _запомнить(user_id, автор, сообщение)
    
    текст = сообщение.lower().strip()
    текст = re.sub(r"@lazur[-_ ]?lite\s*", "", текст).strip()
    
    if not текст: 
        return "Я здесь."

    # 1. Утилиты
    if у := _утилиты(текст): 
        return у
        
    # 2. Сленг
    текст = _сленг(текст)
    
    # 3. Эмоции
    if э := _эмоции(текст): 
        return э

    # 4. Контекст
    if re.search(r"\b(а\s+у\s+тебя|у\s+тебя\s+как|а\s+ты)\b", текст):
        тема = _темы.get(user_id)
        if тема == "приветствие": 
            return "У меня всё отлично! Работаю в Starch."
        if тема == "еда": 
            return "Я не ем, но звучит вкусно!"

    # 5. Интенты (как дела)
    if re.search(r"как дела", текст):
        _задать_тему(user_id, "приветствие")
        return random.choice(["Хорошо, спасибо!", "Всё отлично."])
        
    if re.search(r"есть|кушать|голод", текст):
        _задать_тему(user_id, "еда")
        return random.choice(["Пицца — топ.", "Покушай, я подожду."])

    # 6. Правила
    for regex, ответы in ПРАВИЛА:
        if re.search(regex, текст):
            ответ = random.choice(ответы)
            return ответ.format(имя=мое_имя if мое_имя else "друг")

    # 7. Опечатки
    слова_юзера = re.findall(r"[а-яa-z]+", текст)
    for слово in слова_юзера:
        for эталон in ["привет", "пока", "спасибо", "как", "дела", "шутка", "кофе", "пицца", "кот"]:
            if _похоже(слово, эталон):
                испр = текст.replace(слово, эталон)
                for regex, ответы in ПРАВИЛА:
                    if re.search(regex, испр): 
                        return random.choice(ответы).format(имя=мое_имя)
                if эталон in АССОЦИАЦИИ: 
                    return random.choice(АССОЦИАЦИИ[эталон])

    # 8. Ассоциации
    корни = [_корень(w) for w in re.findall(r"\w+", текст)]
    for ключ, ответы in АССОЦИАЦИИ.items():
        if any(ключ == к or ключ in к or к.startswith(ключ) for к in корни):
            return random.choice(ответы)

    # 9. Вопрос
    if "?" in текст:
        return random.choice(["Хороший вопрос.", "Не знаю.", "А сам как думаешь?"])
        
    # 10. Злость (если не поймали в EQ)
    if re.search(r"\b(бесит|злит|ненавижу|надоело|тупые|идиоты|задолбали|достало|раздражает)\b", текст):
         return random.choice(["Понимаю. Иногда всё бесит.", "Сочувствую. Выговорись.", "Давай выдохнем."])

    # 11. Умное эхо
    слова = [s for s in re.findall(r"[А-Яа-яA-Za-z]{4,}", текст)]
    if слова:
        главное = random.choice(слова)
        if "?" in текст:
            return random.choice([f"А что именно про «{главное}»?", f"Хороший вопрос про «{главное}»."])
        return random.choice([f"«{главное}» — интересная тема.", f"Расскажи про «{главное}»."])

    return "Расскажи подробнее."